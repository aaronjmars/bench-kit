"""Generate README latest block, RESULTS.md and runs/INDEX.md from manifests."""

from __future__ import annotations

import math
import re
from pathlib import Path

from . import stats
from .io import Run, discover

START = "<!-- bench:latest:start -->"
END = "<!-- bench:latest:end -->"
GEN_NOTE = "Generated by bench-kit render from runs/*/manifest.json. Do not edit by hand."


SIG = 3


def fixed(x: float, decimals: int, signed: bool = False, strip: bool = True, min_decimals: int = 0) -> str:
    """x with `decimals` places when |x| >= 1 (or x is 0); below 1, SIG significant figures so small
    values such as $0.00042 do not print as 0. Trailing zeros are stripped down to min_decimals."""
    if x != 0 and math.isfinite(x) and abs(x) < 1:
        decimals = max(min_decimals, SIG - 1 - math.floor(math.log10(abs(x))))
        # rounding can carry to the next power of ten (0.9996 -> 1.00); re-derive from the rounded value
        if abs(round(x, decimals)) >= 1:
            decimals = max(min_decimals, SIG - 1)
    s = f"{x:+.{decimals}f}" if signed else f"{x:.{decimals}f}"
    if strip and "." in s:
        whole, frac = s.split(".")
        frac = frac.rstrip("0")
        frac = frac + "0" * (min_decimals - len(frac))
        s = whole + ("." + frac if frac else "")
    return s


def num(x, signed: bool = False) -> str:
    if x is None:
        return "n/a"
    if isinstance(x, bool) or not isinstance(x, (int, float)):
        return str(x)
    s = fixed(x, 3, signed)
    return "0" if s in ("+0", "-0", "") else s


def ci_text(unc: dict | None) -> str:
    """ " [lower, upper]", or " [CI n/a: why]" when there is no real interval. A stored zero-width interval
    (e.g. from an older bench-kit) is not printed: [0.958, 0.958] would read as perfect certainty."""
    unc = unc or {}
    ci = unc.get("confidence_interval")
    if ci and ci["lower"] == ci["upper"]:
        return " [CI n/a: zero width]"
    if not ci:
        return f" [CI n/a: {unc['no_interval_reason']}]" if unc.get("no_interval_reason") else ""
    return f" [{num(ci['lower'])}, {num(ci['upper'])}]"


def money(x) -> str:
    if x is None:
        return "n/a"
    if x != 0 and abs(x) < 1:
        return ("-" if x < 0 else "") + "$" + fixed(abs(x), 2, min_decimals=2)
    return f"${x:,.2f}"


def minutes(seconds) -> str:
    v = seconds / 60
    return f"{fixed(v, 1, strip=0 < abs(v) < 1)} min"


def date_of(m: dict) -> str:
    return str(m.get("started_at") or "")[:10]


def subject_label(s: dict) -> str:
    parts = []
    h = s.get("harness") or {}
    if h:
        parts.append(h["name"] + (f"@{h['version']}" if h.get("version") else ""))
    mi = s.get("model_info") or {}
    if mi:
        parts.append(mi["id"] + (f" via {mi['inference_platform']}" if mi.get("inference_platform") else ""))
    return " + ".join(parts) or s["name"]


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def subset_text(sd: dict) -> str:
    """ " (4 of 6 tasks; 1 row with no value counted as 0)" for a metric computed over a task subset, else ""."""
    sub = sd.get("subset")
    if not sub:
        return ""
    parts = [f"{sub.get('tasks')} of {plural(sub.get('of') or 0, 'task')}"]
    if sub.get("rows_zeroed"):
        parts.append(f"{plural(sub['rows_zeroed'], 'row')} with no value counted as 0")
    if sub.get("rows_excluded"):
        parts.append(f"{plural(sub['rows_excluded'], 'row')} with no value left out")
    return " (" + "; ".join(parts) + ")"


def score_text(sd: dict) -> str:
    return f"{num(sd.get('score'))}{ci_text(sd.get('uncertainty'))}{subset_text(sd)}"


def subset_rule(cfg: dict) -> str:
    """How a metric picks its tasks and values, e.g. "metadata.kind = clean, value from metadata.x, no value left out"."""
    params = cfg.get("metric_parameters") or {}
    parts = []
    ft = stats.filter_text(cfg)
    if ft:
        parts.append(f"tasks where {ft}")
    if params.get("field"):
        parts.append(f"value from {params['field']}")
    if params.get("missing") == "zero":
        parts.append("no value counts as 0")
    elif params.get("missing") == "excluded":
        parts.append("rows with no value left out")
    return ", ".join(parts)


def primary_line(m: dict, s: str) -> str:
    pm = m.get("primary_metric")
    sd = (m.get("evaluation_results") or {}).get(s, {}).get(pm)
    if not sd:
        return "n/a"
    return score_text(sd)


def comparison_line(c: dict) -> str:
    unc = c.get("uncertainty") or {}
    n = unc.get("num_samples")
    wtl = ""
    if c.get("wins") is not None:
        wtl = f", W/T/L {c['wins']}/{c['ties']}/{c['losses']}"
        if c.get("sign_test_p") is not None:
            wtl += f" (sign test p={num(c['sign_test_p'])})"
    note = f". {c['note']}" if c.get("note") else ""
    up = c.get("unpaired") or {}
    shared = ""
    if up.get("baseline") or up.get("candidate"):
        shared = f" shared ({up.get('baseline', 0)} baseline-only and {up.get('candidate', 0)} candidate-only left out)"
    clus = f" in {unc['num_clusters']} clusters" if unc.get("num_clusters") is not None else ""
    return (
        f"{c['candidate']} vs {c['baseline']} on {c['metric_id']}: diff {num(c.get('diff'), True)}"
        f"{ci_text(unc)}, n={n if n is not None else 'n/a'} tasks{shared}{clus}{wtl}{note}"
    )


def by_subject(m: dict) -> dict[str, tuple]:
    """Per-subject (tasks, repeats) when the manifest declares uneven counts; empty otherwise."""
    sd = m.get("source_data") or {}
    rp = m.get("repeats") or {}
    nt, nr = sd.get("n_completed_by_subject") or {}, rp.get("completed_by_subject") or {}
    if not nt and not nr:
        return {}
    out = {}
    for s in m.get("subjects", []):
        name = s["name"]
        out[name] = (nt.get(name, sd.get("n_completed")), nr.get(name, rp.get("completed")))
    return out


def tasks_line(m: dict) -> str:
    sd = m.get("source_data") or {}
    rp = m.get("repeats") or {}
    base = f"{sd.get('dataset_name')} v{sd.get('version')}, {sd.get('n_completed')} of {sd.get('n_planned')} tasks x {rp.get('completed')} repeats"
    per = by_subject(m)
    if per:
        base += " (per subject, tasks x repeats: " + ", ".join(f"{k} {t} x {r}" for k, (t, r) in per.items()) + ")"
    return base


def judge_line(m: dict) -> str:
    j = m.get("llm_scoring")
    if not j:
        return "none"
    ids = ", ".join(x["model_info"]["id"] for x in j.get("judges", []))
    extra = f", prompt sha {j['input_prompt_sha']}" if j.get("input_prompt_sha") else ""
    return f"{ids} x{j.get('votes', 1)}{extra}"


def cost_line(m: dict) -> str:
    c = m.get("cost") or {}
    s = f"{money(c.get('usd'))} total, {c.get('basis')} basis"
    if c.get("prices_as_of"):
        s += f", prices as of {c['prices_as_of']}"
    if c.get("note"):
        s += f" ({c['note']})"
    secs = m.get("seconds")
    if secs is not None:
        s += f". Time: {minutes(secs)}"
    return s


def errors_line(m: dict) -> str:
    e = m.get("errors") or {}
    by = e.get("by_source") or {}
    src = ", ".join(f"{k} {v}" for k, v in by.items() if v)
    s = f"{e.get('n', 0)} of {e.get('of', 0)}" + (f" ({src})" if src else "") + f", counted as {e.get('counted_as')}"
    if e.get("note"):
        s += f". {e['note']}"
    return s


def results_block(run: Run) -> str:
    m = run.manifest
    title = m.get("title") or m.get("question", "")
    L = [f"## {m['id']}: {title}" if m.get("title") else f"## {m['id']}", ""]
    L.append(f"- Date: {date_of(m)}. Question: {m.get('question')}")
    if m.get("decision_rule"):
        L.append(f"- Decision rule (set before run): {m['decision_rule']}")
    subj = "; ".join(f"{s['name']} ({subject_label(s)})" for s in m.get("subjects", []))
    L.append(f"- Compared: {subj}")
    setup = m.get("setup", "standard")
    if setup == "custom" and m.get("setup_notes"):
        setup += f" ({m['setup_notes']})"
    L.append(f"- Tasks: {tasks_line(m)}. Setup: {setup}. Judge: {judge_line(m)}")
    rules = [
        f"{mid}: {subset_rule(cfg)}"
        for mid, cfg in (m.get("metric_config") or {}).items()
        if stats.computable(cfg) and stats.is_subset_metric(cfg) and subset_rule(cfg)
    ]
    if rules:
        L.append(f"- Metric subsets: {'; '.join(rules)}")
    pm = m.get("primary_metric")
    prim = "; ".join(f"{s['name']} {primary_line(m, s['name'])}" for s in m.get("subjects", []))
    L.append(f"- Primary ({pm}): {prim}")
    others = []
    for mid in m.get("metric_config") or {}:
        if mid == pm:
            continue
        vals = []
        for s in m.get("subjects", []):
            sd = (m.get("evaluation_results") or {}).get(s["name"], {}).get(mid)
            if sd:
                vals.append(f"{s['name']} {score_text(sd)}")
        if vals:
            others.append(f"{mid}: " + ", ".join(vals))
    if others:
        L.append(f"- Other metrics: {'; '.join(others)}")
    for c in m.get("comparisons") or []:
        L.append(f"- Comparison: {comparison_line(c)}")
    L.append(f"- Errors: {errors_line(m)}")
    L.append(f"- Cost: {cost_line(m)}")
    L.append(f"- Verdict: {m.get('verdict')}. Status: {m.get('status')}")
    if m.get("summary"):
        L.append(f"- Summary: {m['summary']}")
    for cw in m.get("compared_with") or []:
        L.append(f"- Compared with: {cw['id']} ({cw['differs']})")
    raw = m.get("raw") or {}
    ev = f"runs/{run.dir.name}/"
    if raw.get("kept") is False:
        ev += f" (raw not kept: {raw.get('reason') or raw.get('location') or 'no reason given'})"
    elif raw.get("location"):
        ev += f" (raw: {raw['location']})"
    if m.get("writeup"):
        ev += f". Write-up: {m['writeup']}"
    L.append(f"- Evidence: {ev}")
    if m.get("superseded_by"):
        L.append(f"- Superseded by: {m['superseded_by']}")
    corr = m.get("corrections") or []
    if corr:
        for c in corr:
            what = f" {c['field']}: {c.get('old')} -> {c.get('new')}." if c.get("field") else ""
            L.append(f"- Correction {c['date']} ({c['author']}):{what} {c['reason']}")
    else:
        L.append("- Corrections: none")
    return "\n".join(L)


def render_results(runs: list[Run], bench: str) -> str:
    head = [f"# {bench} results", "", GEN_NOTE, "", "Every run, newest first. Method and changelog: METHOD.md. Open work: NEXT.md.", ""]
    if not runs:
        return "\n".join(head + ["No runs yet.", ""])
    return "\n".join(head) + "\n" + "\n\n".join(results_block(r) for r in runs) + "\n"


def render_index(runs: list[Run]) -> str:
    L = ["# Runs", "", GEN_NOTE, "", "| Run | Date | Question | Verdict | Status |", "|---|---|---|---|---|"]
    for r in runs:
        m = r.manifest
        q = str(m.get("question", "")).replace("|", "/")
        L.append(f"| [{m.get('id')}]({r.dir.name}/) | {date_of(m)} | {q} | {m.get('verdict')} | {m.get('status')} |")
    return "\n".join(L) + "\n"


def latest_run(runs: list[Run]) -> Run | None:
    """Newest complete, not superseded run; runs marked headline win over the rest."""
    live = [r for r in runs if r.manifest.get("status") == "complete" and not r.manifest.get("superseded_by")]
    for r in live:
        if r.manifest.get("headline"):
            return r
    return live[0] if live else (runs[0] if runs else None)


def render_latest(runs: list[Run]) -> str:
    r = latest_run(runs)
    if r is None:
        return "No runs yet."
    m = r.manifest
    pm = m.get("primary_metric")
    unit = ((m.get("metric_config") or {}).get(pm) or {}).get("metric_unit")
    L = [
        f"Run {m['id']} ({date_of(m)}): {m.get('question')}",
        f"Tasks: {tasks_line(m)}. Judge: {judge_line(m)}.",
        "",
        f"| Subject | {pm}{f' ({unit})' if unit else ''}, mean [95% CI] | n tasks | cost/task | time/task |",
        "|---|---|---|---|---|",
    ]
    per = (m.get("cost") or {}).get("per_subject") or {}
    for s in m.get("subjects", []):
        name = s["name"]
        sd = (m.get("evaluation_results") or {}).get(name, {}).get(pm) or {}
        n = (sd.get("uncertainty") or {}).get("num_samples", "n/a")
        ps = per.get(name, {})
        t = ps.get("seconds_per_task")
        L.append(
            f"| {name} | {primary_line(m, name)} | {n} | {money(ps.get('usd_per_task')) if ps.get('usd_per_task') is not None else 'n/a'}"
            f" | {minutes(t) if t is not None else 'n/a'} |"
        )
    L.append("")
    for c in m.get("comparisons") or []:
        L.append(f"Comparison: {comparison_line(c)}.")
    L.append(f"Verdict: {m.get('verdict')}. Status: {m.get('status')}.")
    if m.get("summary"):
        L.append(f"Summary: {m['summary']}")
    L.append("Every run: RESULTS.md.")
    return "\n".join(L)


def splice_readme(text: str, block: str) -> str | None:
    """README with the latest block replaced; None when the markers are missing."""
    pat = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pat.search(text):
        return None
    return pat.sub(lambda _: f"{START}\n{block}\n{END}", text, count=1)


def bench_name(root: Path, runs: list[Run]) -> str:
    for r in runs:
        if r.manifest.get("bench"):
            return r.manifest["bench"]
    return root.resolve().name


def outputs(root: Path) -> dict[Path, str]:
    """Every generated file and its expected content."""
    runs = discover(root)
    out = {root / "RESULTS.md": render_results(runs, bench_name(root, runs)), root / "runs" / "INDEX.md": render_index(runs)}
    readme = root / "README.md"
    if readme.exists():
        new = splice_readme(readme.read_text(), render_latest(runs))
        if new is not None:
            out[readme] = new
    return out


def render(root: Path) -> list[Path]:
    changed = []
    for path, content in outputs(root).items():
        if not path.exists() or path.read_text() != content:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
            changed.append(path)
    return changed
